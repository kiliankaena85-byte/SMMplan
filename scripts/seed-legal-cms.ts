async function main() {
  console.log('Seeding legal CMS pages...');

  const pages = [
    {
      slug: 'terms',
      title: 'Договор публичной оферты',
      metaTitle: 'Договор публичной оферты',
      metaDescription: 'Договор публичной оферты на оказание услуг по продвижению в социальных сетях',
      contentHtml: termsHtml,
      type: 'PAGE' as any,
    },
    {
      slug: 'privacy',
      title: 'Политика конфиденциальности',
      metaTitle: 'Политика конфиденциальности',
      metaDescription: 'Политика конфиденциальности и обработки персональных данных',
      contentHtml: privacyHtml,
      type: 'PAGE' as any,
    },
    {
      slug: 'refund',
      title: 'Политика возврата',
      metaTitle: 'Политика возврата (Refund Policy)',
      metaDescription: 'Политика возврата денежных средств и гарантийные обязательства.',
      contentHtml: refundHtml,
      type: 'PAGE' as any,
    }
  ];

  for (const page of pages) {
    await prisma.contentItem.upsert({
      where: { slug: page.slug },
      update: {
        contentHtml: page.contentHtml,
        title: page.title,
        metaTitle: page.metaTitle,
        metaDescription: page.metaDescription,
        isPublished: true,
      },
      create: {
        slug: page.slug,
        title: page.title,
        contentHtml: page.contentHtml,
        metaTitle: page.metaTitle,
        metaDescription: page.metaDescription,
        type: page.type,
        isPublished: true,
      },
    });
    console.log(`Upserted page: ${page.slug}`);
  }

  console.log('Done!');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
