# -*- coding: utf-8 -*-
"""
Generator script for SMMplan Strategic & Operational Marketing Plan in DOCX.
PRE-REVENUE COLD-START EDITION WITH DEEP CHANNEL & CONTENT BREAKDOWN.

Complies with formal documentation standards:
- Font: Times New Roman throughout
- Margins: Left 25mm, Right 20mm, Top 20mm, Bottom 20mm
- Body text: 14pt, 1.5 line spacing, Justified, 12.5mm first line indent
- Headings: 14pt Bold, no trailing period, keep_with_next=True
- Tables: Times New Roman 11pt, clean black borders, header row bold
- Header: Arabic page numbers top right starting from page 2
- Strictly NO mention of Rospatent, GOST, FIPS, etc.
"""

import os
import shutil
import docx
from docx.shared import Pt, Mm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml import parse_xml
from docx.oxml.ns import nsdecls

def create_document():
    doc = docx.Document()

    # --- Section Margins & Page Size (A4) ---
    section = doc.sections[0]
    section.page_width = Mm(210)
    section.page_height = Mm(297)
    section.top_margin = Mm(20)
    section.bottom_margin = Mm(20)
    section.left_margin = Mm(25)
    section.right_margin = Mm(20)

    # Different first page for header
    section.different_first_page_header_footer = True

    # Setup page number in header for subsequent pages
    header = section.header
    header_p = header.paragraphs[0]
    header_p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    header_run = header_p.add_run()
    header_run.font.name = 'Times New Roman'
    header_run.font.size = Pt(12)
    header_run.font.color.rgb = RGBColor(0, 0, 0)
    fld1 = parse_xml(f'<w:fldChar {nsdecls("w")} w:fldCharType="begin"/>')
    instr = parse_xml(f'<w:instrText {nsdecls("w")} xml:space="preserve"> PAGE </w:instrText>')
    fld2 = parse_xml(f'<w:fldChar {nsdecls("w")} w:fldCharType="separate"/>')
    fld3 = parse_xml(f'<w:fldChar {nsdecls("w")} w:fldCharType="end"/>')
    header_run._r.append(fld1)
    header_run._r.append(instr)
    header_run._r.append(fld2)
    header_run._r.append(fld3)

    # Base Normal Style setup
    normal_style = doc.styles['Normal']
    normal_style.font.name = 'Times New Roman'
    normal_style.font.size = Pt(14)
    normal_style.font.color.rgb = RGBColor(0, 0, 0)
    normal_style.paragraph_format.line_spacing = 1.5
    normal_style.paragraph_format.space_before = Pt(0)
    normal_style.paragraph_format.space_after = Pt(0)
    normal_style.paragraph_format.first_line_indent = Mm(12.5)
    normal_style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    # Helpers
    def add_p(text, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY, space_before=0, space_after=0, indent=True):
        p = doc.add_paragraph()
        p.alignment = align
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_before = Pt(space_before)
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.first_line_indent = Mm(12.5) if indent else Mm(0)
        
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)
        run.bold = bold
        run.italic = italic
        run.font.color.rgb = RGBColor(0, 0, 0)
        return p

    def add_h1(text):
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_before = Pt(14)
        p.paragraph_format.space_after = Pt(6)
        p.paragraph_format.first_line_indent = Mm(12.5)
        p.paragraph_format.keep_with_next = True
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)
        run.bold = True
        run.font.color.rgb = RGBColor(0, 0, 0)
        return p

    def add_h2(text):
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_before = Pt(10)
        p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.first_line_indent = Mm(12.5)
        p.paragraph_format.keep_with_next = True
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)
        run.bold = True
        run.font.color.rgb = RGBColor(0, 0, 0)
        return p

    def add_h3(text):
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_before = Pt(8)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.first_line_indent = Mm(12.5)
        p.paragraph_format.keep_with_next = True
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        
        run = p.add_run(text)
        run.font.name = 'Times New Roman'
        run.font.size = Pt(14)
        run.bold = True
        run.italic = True
        run.font.color.rgb = RGBColor(0, 0, 0)
        return p

    def format_table(tbl, col_widths, headers, rows):
        tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
        tblPr = tbl._tbl.tblPr
        borders = parse_xml(
            f'<w:tblBorders {nsdecls("w")}>\n'
            '  <w:top w:val="single" w:sz="4" w:space="0" w:color="000000"/>\n'
            '  <w:bottom w:val="single" w:sz="4" w:space="0" w:color="000000"/>\n'
            '  <w:left w:val="single" w:sz="4" w:space="0" w:color="000000"/>\n'
            '  <w:right w:val="single" w:sz="4" w:space="0" w:color="000000"/>\n'
            '  <w:insideH w:val="single" w:sz="4" w:space="0" w:color="000000"/>\n'
            '  <w:insideV w:val="single" w:sz="4" w:space="0" w:color="000000"/>\n'
            '</w:tblBorders>'
        )
        tblPr.append(borders)

        # Header
        hdr_row = tbl.rows[0]
        hdr_tr = hdr_row._tr.get_or_add_trPr()
        hdr_tr.append(parse_xml(f'<w:tblHeader {nsdecls("w")}/>'))
        hdr_tr.append(parse_xml(f'<w:cantSplit {nsdecls("w")}/>'))

        for idx, title in enumerate(headers):
            cell = hdr_row.cells[idx]
            cell.width = Mm(col_widths[idx])
            tcPr = cell._tc.get_or_add_tcPr()
            shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="F2F2F2"/>')
            tcPr.append(shd)
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.line_spacing = 1.0
            p.paragraph_format.space_before = Pt(3)
            p.paragraph_format.space_after = Pt(3)
            p.paragraph_format.first_line_indent = Mm(0)
            run = p.add_run(title)
            run.font.name = 'Times New Roman'
            run.font.size = Pt(11)
            run.bold = True
            run.font.color.rgb = RGBColor(0, 0, 0)

        # Data rows
        for r_idx, row_data in enumerate(rows):
            row = tbl.rows[r_idx + 1]
            trPr = row._tr.get_or_add_trPr()
            trPr.append(parse_xml(f'<w:cantSplit {nsdecls("w")}/>'))
            for c_idx, val in enumerate(row_data):
                cell = row.cells[c_idx]
                cell.width = Mm(col_widths[c_idx])
                p = cell.paragraphs[0]
                align = WD_ALIGN_PARAGRAPH.CENTER if c_idx > 0 and len(str(val)) < 22 else WD_ALIGN_PARAGRAPH.LEFT
                p.alignment = align
                p.paragraph_format.line_spacing = 1.15
                p.paragraph_format.space_before = Pt(2)
                p.paragraph_format.space_after = Pt(2)
                p.paragraph_format.first_line_indent = Mm(0)
                run = p.add_run(str(val))
                run.font.name = 'Times New Roman'
                run.font.size = Pt(11)
                run.font.color.rgb = RGBColor(0, 0, 0)

    # ==================== ТИТУЛЬНЫЙ ЛИСТ ====================
    add_p('ПЛАТФОРМА АВТОМАТИЗАЦИИ МАРКЕТИНГА В СОЦИАЛЬНЫХ СЕТЯХ SMMPLAN', bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, space_before=30, space_after=10, indent=False)
    add_p('НАПРАВЛЕНИЕ СТРАТЕГИЧЕСКОГО РАЗВИТИЯ И ВЫВОДА ПРОДУКТА НА РЫНОК', bold=False, align=WD_ALIGN_PARAGRAPH.CENTER, space_before=0, space_after=60, indent=False)

    add_p('СТРАТЕГИЧЕСКИЙ И ОПЕРАЦИОННЫЙ ПЛАН ВЫВОДА НА РЫНОК И ХОЛОДНОГО ПУСКА (COLD START)', bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, space_before=20, space_after=10, indent=False)
    add_p('ДЕТАЛЬНАЯ КАРТОГРАФИЯ УСЛУГ, ПЛОЩАДОК РАЗМЕЩЕНИЯ И КОНТЕНТНЫХ СЦЕНАРИЕВ ДЛЯ ПРИВЛЕЧЕНИЯ ПЕРВЫХ КЛИЕНТОВ', bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, space_before=0, space_after=20, indent=False)
    add_p('(Разработано для этапа Pre-revenue с опорой на эмпирические данные анализа 1,95 млн рыночных транзакций и опыт конкурентов)', italic=True, align=WD_ALIGN_PARAGRAPH.CENTER, space_before=0, space_after=120, indent=False)

    add_p('Москва, 2026 год', align=WD_ALIGN_PARAGRAPH.CENTER, space_before=80, space_after=0, indent=False)

    doc.add_page_break()

    # ==================== РАЗДЕЛ 1 ====================
    add_h1('1. Исходная ситуация платформы и цели холодного пуска')

    add_h2('1.1. Статус проекта: этап вывода на рынок (Pre-revenue)')
    add_p('Платформа SMMplan (домены smmplan.pro и обслуживаемые витрины на ядре OmniSMM 1.0) находится на предстартовом этапе (Pre-revenue). На текущий момент у проекта отсутствует регулярная коммерческая выручка, сформированная клиентская база и наработанный входящий поисковый трафик.')
    add_p('Технологическая часть платформы полностью развернута: реализована современная архитектура (Next.js 16, React 19, Prisma 5), подключены проверенные поставщики услуг с автоматическим исполнением, внедрены защитные механизмы Drip-Feed и фискализация по стандарту 54-ФЗ. Таким образом, технологический барьер преодолен, и ключевым фактором успеха становится решение проблемы «холодного пуска» (Cold Start) — привлечение первых 100, 500 и 1 000 платящих клиентов в условиях строго ограниченного стартового бюджета.')

    add_h2('1.2. Рыночный бенчмаркинг: потенциал ниши на основе анализа ERP-данных конкурентов')
    add_p('Для оценки емкости рынка и выбора оптимальной модели продвижения был выполнен глубокий анализ массива реальных данных конкурентов из ERP-системы (1 948 563 заказа и 964 тыс. финансовых операций, включая 83 рекламные кампании лидера ниши PrimeLike). Рыночные ориентиры представлены в таблице 1.')

    add_p('Таблица 1 — Ключевые метрики сформированного рынка SMM-панелей (по данным ERP-анализа)', italic=True, indent=False)
    tbl1 = doc.add_table(rows=7, cols=3)
    tbl1_widths = [85, 45, 35]
    tbl1_headers = ['Параметр рынка / Бенчмарк', 'Значение у лидера рынка', 'Значение для SMMplan']
    tbl1_rows = [
        ['Ежемесячный объем выручки зрелой панели, руб.', '4,5 – 6,3 млн', 'Целевой ориентир (к 12 мес.)'],
        ['Средний чек одной завершенной покупки (AOV), руб.', '68 – 74', 'Плановый: 70 руб.'],
        ['Средняя пожизненная ценность клиента (LTV), руб.', '400,31', 'Плановый: 250–350 руб.'],
        ['Доля повторных покупателей в базе, %', '51,0%', 'Целевой порог: не менее 50%'],
        ['Конверсия из визита в регистрацию (лендинг), %', '12 – 16%', 'Целевой ориентир: 15%'],
        ['Стоимость привлечения клиента в SEO (CAC), руб.', '8,44', 'Предельный ориентир: ≤ 20 руб.']
    ]
    format_table(tbl1, tbl1_widths, tbl1_headers, tbl1_rows)

    add_h2('1.3. Стратегическая задача холодного пуска')
    add_p('Главный вывод из анализа рынка: лидирующий конкурент достиг оборота в 70,7 млн рублей исключительно за счет поискового трафика Яндекса, сгенерированного 83 статьями-листиклами на внешних медиаресурсах. У него нет высокобюджетной медийной рекламы или огромного штата маркетологов.')
    add_p('Задача SMMplan на этапе 0 руб. выручки — не повторять затратные ошибки масштабирования, а реализовать бережливую (Lean) стратегию запуска: получить первые заказы через бесплатные и микро-бюджетные каналы, обкатать конверсию сайта и воронку удержания, после чего реинвестировать 100% первой поступающей прибыли в расширение присутствия в поисковой выдаче.')

    # ==================== РАЗДЕЛ 2 ====================
    add_h1('2. Целевые ориентиры этапов запуска платформы')

    add_h2('2.1. Фазовый переход от 0 к регулярной выручке')
    add_p('Процесс вывода платформы на окупаемость разделен на четыре последовательные фазы, каждая из которых имеет четкий критерий перехода:')
    add_p('— Фаза 0: «Первые 100 клиентов» (Недели 1–4). Фокус: бесплатные статьи, форумы вебмастеров, ручные посевы, тестирование воронки без крупных затрат. Цель — первые 30 000 руб. оборота;')
    add_p('— Фаза 1: «Точка безубыточности» (Месяцы 2–3). Фокус: ретрофиттинг первых 2–3 индексированных статей, запуск партнерской программы, реинвестирование маржи. Цель — выход на 150 000 руб./мес.;')
    add_p('— Фаза 2: «Разгон маховика» (Месяцы 4–6). Фокус: планомерный выпуск листиклов по проверенным темам (YouTube, Telegram), работа с оптовиками. Цель — 500 000 – 1 000 000 руб./мес.;')
    add_p('— Фаза 3: «Масштабирование» (Месяцы 7–12). Фокус: ретаргетинг, White Label, автоматизация. Цель — от 3 000 000 руб./мес.')

    add_h2('2.2. Контрольные показатели поэтапного роста')
    add_p('В таблице 2 зафиксированы плановые контрольные точки развития сервиса от нулевого базиса до устойчивой операционной прибыли.')

    add_p('Таблица 2 — Контрольные точки перехода платформы от 0 до масштабирования', italic=True, indent=False)
    tbl2 = doc.add_table(rows=6, cols=5)
    tbl2_widths = [45, 30, 30, 30, 30]
    tbl2_headers = ['Метрика', 'Старт (Фаза 0)', 'Месяц 3 (Фаза 1)', 'Месяц 6 (Фаза 2)', 'Месяц 12 (Фаза 3)']
    tbl2_rows = [
        ['Ежемесячная выручка, руб.', '0', '150 000', '800 000', '3 000 000 – 6 000 000'],
        ['Платящих клиентов в месяц, чел.', '0', '400', '1 800', '8 000 – 15 000'],
        ['Новых регистраций в месяц, чел.', '0 – 50', '800', '3 500', '12 000'],
        ['Заказов в месяц, шт.', '0', '1 500', '8 500', '50 000+'],
        ['Удержание клиентов M1 Retention, %', 'Тест', '6,0%', '8,0%', '10,0%']
    ]
    format_table(tbl2, tbl2_widths, tbl2_headers, tbl2_rows)

    # ==================== РАЗДЕЛ 3 ====================
    add_h1('3. Детальная спецификация услуг: что конкретно продает платформа')

    add_h2('3.1. Эмпирические приоритеты категорий по данным рыночного анализа')
    add_p('На старте при нулевом бюджете категорически запрещается распылять маркетинговые усилия на всю широкую линейку каталога. Анализ массива транзакций выявил четкую сегментацию отдачи:')
    add_p('— Направление YouTube обеспечивает наибольший прирост выручки (+20,5%) и привлекает клиентов с чеком, превышающим средний по рынку в 2,5 раза;')
    add_p('— Направление Telegram демонстрирует максимальную частоту повторных покупок (+11,6% к выручке) и обеспечивает удержание;')
    add_p('— Направление ВКонтакте формирует массовый недорогой поток заказов (+5,1% выручки, +9,2% заказов);')
    add_p('— Направление TikTok показывает отрицательную динамику (-16,1% выручки) и подлежит полному исключению из маркетинговых расходов.')

    add_h2('3.2. Детальная расшифровка спроса в категории YouTube')
    add_p('В сегменте YouTube пользователи приобретают конкретные технологические типы услуг, ориентированные на решение конкретных задач автора контента:')
    add_p('1. Просмотры коротких видео (YouTube Shorts Views). Высокоскоростные просмотры с быстрым зачислением в первые 1–3 часа после публикации видео. Цель закупки — пробитие порога алгоритма и вывод ролика в ленту рекомендаций Shorts. Характеризуются низкой себестоимостью и массовым спросом (пакеты от 1 000 до 50 000 просмотров).')
    add_p('2. Просмотры длинных видео с высоким удержанием (High Retention Long-Form Views). Видео просматривается ботами/офферами на протяжении от 3 до 10+ минут с естественным распределением глубины просмотра. Это критически важно для алгоритма ранжирования YouTube: удержание свыше 50% хронометража поднимает видео в поисковой выдаче видеохостинга и блоке «Следующее».')
    add_p('3. Часы просмотров для монетизации (Watch Time Hours). Самый высокомаржинальный пакет в каталоге (чек от 1 500 до 5 000 рублей). Автору канала требуется набрать 4 000 часов просмотров за последние 12 месяцев для подключения официальной партнерской программы YouTube (YPP). Платформа предоставляет специализированные просмотры длинных часовых стримов с 100% удержанием.')
    add_p('4. Подписчики YouTube (Subscribers). Услуга с гарантией от списаний (Refill 30 дней) для набора порога в 1 000 подписчиков (второе требование монетизации YPP) и создания социального доказательства.')
    add_p('5. Лайки и тематические комментарии. Инструмент балансировки активности (нормальное соотношение для алгоритма: 1 лайк на 15–25 просмотров). Комментарии пишутся по теме видео на русском языке реальными профилями.')

    add_h2('3.3. Детальная расшифровка спроса в категории Telegram')
    add_p('В экосистеме Telegram спрос формируется преимущественно владельцами коммерческих и контентных каналов со следующей структурой:')
    add_p('1. Подписчики каналов и групп (Channel Members). Подразделяются на офферных (дешевые аккаунты для формирования первичной видимой массы перед стартом официальной рекламы) и живых подписчиков из РФ и стран СНГ.')
    add_p('2. Просмотры постов (Post Views). Разовое начисление просмотров на конкретные публикации. Критически востребовано администраторами каналов перед продажей рекламных мест на биржах (Telega.in, биржи в Telegram) для удержания видимого коэффициента вовлеченности (ERR) на уровне 20–30%.')
