async function main() {
  console.log("Seeding legal pages with gsd-corporate-legal-team methodology...");

  await prisma.systemSettings.updateMany({
    where: { id: "global" },
    data: { legalCompanyName: "ИП Соколов Артём Андреевич" }
  });
  
  for (const page of legalPages) {
    const existing = await prisma.contentItem.findUnique({
      where: { slug: page.slug }
    });

    if (existing) {
      await prisma.contentItem.update({
        where: { slug: page.slug },
        data: {
          title: page.title,
          contentHtml: page.contentHtml,
          isPublished: true,
          type: "PAGE",
        }
      });
      console.log(`Updated page: /legal/${page.slug}`);
    } else {
      await prisma.contentItem.create({
        data: {
          slug: page.slug,
          title: page.title,
          contentHtml: page.contentHtml,
          isPublished: true,
          type: "PAGE",
        }
      });
      console.log(`Created page: /legal/${page.slug}`);
    }
  }

  // Delete old 'rules' slug if it existed separately before merging
  try {
    const rulesExisting = await prisma.contentItem.findUnique({
      where: { slug: "rules" }
    });
    if (rulesExisting) {
      await prisma.contentItem.delete({
        where: { slug: "rules" }
      });
      console.log("Deleted old 'rules' page as it is now merged into 'terms'.");
    }
  } catch (e) {
    // Ignore error if it doesn't exist
  }

  console.log("Seeding completed successfully!");
}

