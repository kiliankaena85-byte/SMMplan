def safe_save(doc, target_path):
    try:
        doc.save(target_path)
        print(f'Successfully saved: {target_path}')
        return target_path
    except PermissionError:
        base, ext = os.path.splitext(target_path)
        alt_path = f'{base}_v2{ext}'
        doc.save(alt_path)
        print(f'Original file locked by Word. Saved to alternate path: {alt_path}')
        return alt_path

